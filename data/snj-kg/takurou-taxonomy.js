  /* ---------- 5. 索引与派生统计（全部实时计算，界面不写死数字） ---------- */
  var BOOKMAP = { "初上": "初级上", "初下": "初级下", "中上": "中级上", "中下": "中级下", "高级": "高级" };

  var LESSON_BY_ID = {};
  LESSONS.forEach(function (l, i) { l.i = i; l.seq = i; LESSON_BY_ID[l.id] = l; });

  var NODE_BY_ID = {};
  NODES.forEach(function (n, i) {
    n.i = i;
    n.pre = [];      /* 直接先修 id */
    n.unlock = [];   /* 可解锁 id */
    /* 课次挂接：初上_14 → ls_初级上_14 */
    var parts = n.ls.split("_");
    n.lessonId = "ls_" + (BOOKMAP[parts[0]] || parts[0]) + "_" + parts[1];
    n.lesson = LESSON_BY_ID[n.lessonId] || null;
    if (n.lesson) n.seq = n.lesson.seq; else n.seq = 0;
    n.rel = 0;       /* 图上真实关系数（先修 + 解锁） */
    NODE_BY_ID[n.id] = n;
  });

  /* 解析边；丢弃指向不存在节点的边并记录，便于数据自检 */
  var EDGE_LIST = [], DROPPED = [];
  EDGES.forEach(function (e) {
    var a = NODE_BY_ID[e[0]], b = NODE_BY_ID[e[1]];
    if (!a || !b) { DROPPED.push(e); return; }
    var exists = EDGE_LIST.some(function (x) {
      return (x.from === e[0] && x.to === e[1]) || (x.from === e[1] && x.to === e[0]);
    });
    if (exists) { DROPPED.push(e); return; }
    EDGE_LIST.push({ from: e[0], to: e[1], kind: e[2] || "soft" });
    a.unlock.push(b.id);
    b.pre.push(a.id);
  });
  NODES.forEach(function (n) { n.rel = n.pre.length + n.unlock.length; });

