ROW_RE = re.compile(r"^\| 上午（精力最好） \| \*\*政治\*\* \| [^|]+ \| .*\|$", re.M)
CHK_RE = re.compile(r"^- \[ \] \*\*政治\*\* .*$", re.M)

for day, (dur, content, chk) in PLAN.items():
    hits = sorted(BASE.glob(day + "-*.md"))
    if not hits:
        print("MISS", day); continue
    p = hits[0]
    s = p.read_text(encoding="utf-8")
    n0 = len(ROW_RE.findall(s)); n1 = len(CHK_RE.findall(s))
    new_row = f"| 上午（精力最好） | **政治** | {dur} | {content} |"
    new_chk = f"- [ ] {chk}"
    s2 = ROW_RE.sub(lambda m: new_row, s, count=1)
    s2 = CHK_RE.sub(lambda m: new_chk, s2, count=1)
    # 校验：没有控制字符
    bad = [c for c in s2 if ord(c) < 9 or (13 < ord(c) < 32)]
    p.write_text(s2, encoding="utf-8")
    print(f"{p.name:34s} 行{n0} 打卡{n1} 控制字符{len(bad)} {'OK' if s2!=s and not bad else 'CHECK'}")
