/**
 * 科目 → **考试科目**（合并视图）。2026-10-25 新增。
 *
 * 为什么需要它：ALIASES 解决的是「同一个名字的错别字」（高等数学 → 高数），
 * 而这里解决的是**另一件事** —— 「同一张卷子被拆成了几个名字」。
 *
 * 真实症状：考试里「计算机」是**一科 200 分**，日志里却记成三个 subject
 * （`C语言` / `数据结构` / `计算机`）。于是 `check-study-log.mjs` 按 subject
 * 逐条比「最近日期」时，报出「计算机 断档 11 天」——
 * 而实际上数据结构昨天刚做、C 语言前天刚做。**断档判据被拆分搞失真**，
 * 结果是催补一门昨天刚学过的课，同时放过真正断档的那门。
 *
 * 用法：断档/覆盖率这类「按科目看」的统计走本表合并；按 subject 明细看时仍用原值。
 * ⚠️ 新增 subject 必须同时登记到这里，否则它会自成一组、继续制造假断档。
 */
export const SUBJECT_GROUP = {
  C语言: '计算机',
  数据结构: '计算机',
  计算机: '计算机',
  高数: '高等数学',
  英语: '英语',
  政治: '政治',
  综合: '综合',
  工具: '工具',
  日语: '日语',
};

/** 取某 subject 的合并科目名；未登记的 subject 原样返回（并在校验器里告警）。 */
export const groupOf = (subject) => SUBJECT_GROUP[subject] || subject;

/**
 * 考点编号正则 —— **单一事实源**（2026-10-25 抽出来）。
 *
 * 为什么抽：这条正则原来在**两个地方各写一份**，而且**两份不一致**：
 *   · `scripts/log-add.mjs`（写入器）   → `[#＃]\s*([CDME])\s*\d{1,3}`  认 C/D/M/E
 *   · `scripts/check-study-log.mjs`（校验器）→ `[#＃]\s*[CME]\s*\d{1,3}`  只认 C/M/E
 * ⇒ 数据结构写 `#D01` 能过写入器、却被校验器判成「无编号」。
 *   2026-10-25 给 quiz 加硬拦时才发现：**照着校验器的正则写新记录，永远过不了校验器**。
 *
 * 编号含义（见 `考点主清单-计算机.json`）：
 *   C = C 语言 · **D = 数据结构**（`D01`–`D09`）· M = 高数 · E = 英语 · P = 政治
 *
 * ⚠️ 2026-10-31 补 P：政治 100 分、4 次真题命中的考点，原来进不了引擎，
 *   只能靠 `--no-id` 豁免 —— 等于政治的错题永远攒不出掌握度。
 *   政治编号规则：`#P` + 章 + 节 + 点，直接对应考点文件名的三段数字。
 *     `00-1-1` → `#P011`　`1-2-2` → `#P122`　`2-3-2` → `#P232`
 *   章号是两位数时自然变成四位（`12-1-1` → `#P1211`），所以上限放到 4 位。
 */
export const RE_KP_ID = /[#＃]\s*([CDMEP])\s*\d{1,4}/;

/** 某条日志是否带考点编号（查 title 与 weak 两处）。 */
export const hasKpId = (e) =>
  RE_KP_ID.test((e.title || '') + ' ' + (e.weak || ''));

