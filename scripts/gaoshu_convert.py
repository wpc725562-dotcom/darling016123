RE_ROUTE = re.compile(r"^\[ROUTE\]:.*$", re.M)
RE_H1 = re.compile(r"^#\s+.*$", re.M)
RE_FOLD = re.compile(r"^>\s*\[!success\]-?\s*点击查看答案与解析\s*$", re.M)


def convert(text: str) -> str:
    text = RE_ROUTE.sub("", text)
    text = RE_H1.sub("", text)
    text = RE_FOLD.sub("【答案与解析】", text)
    # 折叠块内的 > 前缀去掉（仅处理答案块之后的行）
    lines = text.splitlines()
    out, in_ans = [], False
    for ln in lines:
        if ln.strip() == "【答案与解析】":
            in_ans = True
            out.append(ln)
            continue
        if in_ans:
            if ln.startswith(">"):
                ln = ln[1:].lstrip()
            elif ln.strip() == "":
                pass
            elif not ln.startswith((" ", "【")):
                # 答案块结束（遇到新的正文）
                if not ln.startswith(">") and ln.strip() and not ln.startswith("**"):
                    in_ans = False
        out.append(ln)
    text = "\n".join(out)
    # 压缩连续空行
    text = re.sub(r"\n{3,}", "\n\n", text).strip()
    return text


def main():
    os.makedirs(DST, exist_ok=True)
    done = 0
    for rel, ch, ch_name, k, name, freq, qtype in MAP:
        src = os.path.join(SRC, rel)
        if not os.path.exists(src):
            print(f"[缺] {rel}")
            continue
        body = convert(open(src, encoding="utf-8").read())
        safe = name.replace("/", "·").replace("（", "(").replace("）", ")")
        fn = f"G{ch}-{k}-{safe}.txt"
        header = (
            f"【课程】04-高数\n"
            f"【章节】第{ch}章　{ch_name}\n"
            f"【节】第{ch}章 第{k}考点\n"
            f"【考点】G{ch}-{k}　{name}\n"
            f"【考频】{freq}\n"
            f"【题型】{qtype}\n"
            f"{'=' * 60}\n\n"
        )
        footer = (
            f"\n\n{'=' * 60}\n"
            f"【原文锚点】《高等数学》精编讲义 第{ch}章（_raw/gaoshu.txt）\n"
            f"【来源】原 高等数学/{rel}\n"
        )
        open(os.path.join(DST, fn), "w", encoding="utf-8").write(header + body + footer)
        done += 1
    print(f"[完成] 转换 {done} 篇 → {DST}")


if __name__ == "__main__":
    main()
