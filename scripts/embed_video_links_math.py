def fname_ok(name):
    return name.replace(" ", "-")

def embed(fname, rows):
    path = os.path.join(BASE, fname + ".md")
    if not os.path.exists(path):
        return (False, "缺文件: " + fname)
    with open(path, encoding="utf-8") as f:
        body = f.read()
    if "配套视频" in body:
        return (False, "已含: " + fname)
    lines = [MARK, "", "> 复习到本考点 → 先看视频补讲，再刷上面「闭卷挑战」。", ""]
    for t, url, tip in rows:
        if not url:
            lines.append("- " + t)
            continue
        s = (" · " + tip) if tip else ""
        lines.append("- [" + t + "](" + url + ")" + s)
    lines.append("")
    # ★ E2（2026-09-20）：补 newline="\n"，理由同 embed_video_links.py。
    with open(path, "a", encoding="utf-8", newline="\n") as f:
        f.write("\n" + "\n".join(lines) + "\n")
    return (True, "已嵌入: " + fname)

if __name__ == "__main__":
    ok = fail = 0
    for name, rows in MAP.items():
        key = fname_ok(name)
        if not os.path.exists(os.path.join(BASE, key + ".md")):
            print("!! 缺文件", key); fail += 1; continue
        ok_, msg = embed(key, rows)
        print(("OK  " if ok_ else "!!  ") + msg)
        if ok_: ok += 1
        else: fail += 1
    print("完成 %d 篇, 失败 %d" % (ok, fail))
